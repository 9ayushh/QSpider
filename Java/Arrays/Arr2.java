public class Arr2 {
  public static void main(String[] args) {

    // byte
    byte [] a = {1,2,3,4};
    System.out.println(a);
    System.out.println(a.length);
    System.out.println(a.length-1);

    // short
    short [] b = {12,13,354,678,34};
    System.out.println(b);
    System.out.println(b.length);
    System.out.println(b.length-1);

    // int
    int [] c = {34,1234,3456,6787,34567};
    System.out.println(c);
    System.out.println(c.length);
    System.out.println(c.length-1);

    // long
    long [] d = {1234l,2345l,23456l,34567l,8765432l};
    System.out.println(d);
    System.out.println(d.length);
    System.out.println(d.length-1);

    // float
    float [] e = {234.654f,34566.234f,87654.45f};
    System.out.println(e);
    System.out.println(e.length);
    System.out.println(e.length-1);

    // double
    double [] f = {12345.54321,2345.765,4543.4543,3987.78};
    System.out.println(f);
    System.out.println(f.length);
    System.out.println(f.length-1);

    // char
    char [] g = {'A','c','r','K'};
    System.out.println(g);
    System.out.println(g.length);
    System.out.println(g.length-1);

    // boolean
    boolean [] h = {true,false,false,false,true};
    System.out.println(h);
    System.out.println(h.length);
    System.out.println(h.length-1);

    // String
    String [] i = {"asdf","kjh","qwert","reoiuy","zxcvbn","mnbvc"};
    System.out.println(i);
    System.out.println(i.length);
    System.out.println(i.length-1);
  }
}
